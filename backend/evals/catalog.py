def catalog():
    pilot = load_cards()
    result = {}
    for index, line in enumerate(
        SOURCE.read_text(encoding="utf-8-sig").splitlines(), 1
    ):
        if not re.match(r"^\| [A-Z]{3}-\d{2} \|", line):
            continue
        cells = [x.strip() for x in line.strip("|").split("|")]
        key, title, scope = cells[:3]
        group, num = key.split("-")
        if key in result:
            raise ValueError(key)
        record = {
            "id": key,
            "title": title,
            "scope": scope,
            "rubric": cells[3],
            "reference": (cells[4] or cells[3]) if len(cells) > 4 else cells[3],
            "source_line": index,
            "setup": SPECIAL.get(group, "九月快照"),
        }
        if key in pilot:
            card = pilot[key]
            record.update(
                messages=[t["message"] for t in card["turns"]],
                reference=card["turns"][-1]["expected"],
                scoring="pilot_card",
            )
        elif key in MULTI:
            record.update(messages=MULTI[key], scoring="rubric_review")
        elif group not in SPECIAL:
            q = QUESTIONS[group].split("|")[int(num) - 1]
            if key != "LIM-03":
                q = "2026年9月，" + q
            record.update(messages=[q.rstrip("？") + "？"], scoring="rubric_review")
        else:
            record.update(messages=[], scoring="controlled_scenario")
        result[key] = record
    if len(result) != 200 or sum(bool(c["messages"]) for c in result.values()) != 170:
        raise ValueError("核对源清单和问句覆盖")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(
        json.dumps(list(catalog().values()), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
